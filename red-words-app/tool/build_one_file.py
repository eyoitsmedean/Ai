#!/usr/bin/env python3
"""Build one HTML file a phone can open with no server.

Reads the Guest Leaf (index, css, js, pack) and the bundled OFL serif.
Writes red-words-app/guest/RedWords.html. Does not invent sayings.
"""

from __future__ import annotations

import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUEST = ROOT / "guest"
OUT = GUEST / "RedWords.html"


def data_font(path: Path) -> str:
    raw = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:font/ttf;base64,{raw}"


def main() -> None:
    css = (GUEST / "guest.css").read_text(encoding="utf-8")
    css = css.replace(
        'url("../fonts/SourceSerif4.ttf")',
        f'url("{data_font(ROOT / "fonts" / "SourceSerif4.ttf")}")',
    )
    css = css.replace(
        'url("../fonts/SourceSerif4-Italic.ttf")',
        f'url("{data_font(ROOT / "fonts" / "SourceSerif4-Italic.ttf")}")',
    )
    if "url(" in css and "data:font" not in css:
        raise SystemExit("a font url was not inlined")
    if re.search(r"url\(\s*['\"](?!data:)", css):
        raise SystemExit("external css url remains")

    html = (GUEST / "index.html").read_text(encoding="utf-8")
    html = html.replace(
        '<link rel="stylesheet" href="guest.css" />',
        f"<style>\n{css}\n</style>",
    )
    pack = (GUEST / "pack.js").read_text(encoding="utf-8")
    js = (GUEST / "guest.js").read_text(encoding="utf-8")
    html = html.replace(
        '<script src="pack.js"></script>\n  <script src="guest.js"></script>',
        f"<script>\n{pack}\n{js}\n</script>",
    )
    if 'src="' in html or "href=\"guest" in html or "href=\"pack" in html:
        raise SystemExit("external asset reference remains")
    if "anxiety-mt-6-34" not in html or "Matthew 6:34" not in html:
        raise SystemExit("Matthew 6:34 missing from the file")
    if "OneDigital" in html:
        raise SystemExit("OneDigital does not belong in this file")

    banner = (
        "<!-- Red Words guest leaf. One file. Generated by tool/build_one_file.py. "
        "World English Bible, public domain. Do not hand-edit the pack. -->\n"
    )
    if not html.startswith("<!DOCTYPE"):
        raise SystemExit("index lost its doctype")
    html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + banner, 1)
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
