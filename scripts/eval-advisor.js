#!/usr/bin/env node
/* Runs eval/advisor-eval.json through the letterpress — the same engine the server and the
   static page use when no model is present — and writes eval/RESULTS.md.

   Checks per case:
     room      the letter is set from the expected room (or from none, when none should be named)
     crisis    988 / findahelpline stand and no Scripture follows, exactly when the message is a crisis
     canon     every saying is the canonical KJV text of a red-letter verse, from the corpus (none on crisis)
     two       exactly two sayings, or none when counsel must stop
     clean     no {{placeholder}} survives rendering
     echo      none of the writer's words come back as Scripture, and no forbidden phrase appears

   Exit code is the number of failing cases. `--check` only confirms RESULTS.md is current. */
const fs = require('fs');
const path = require('path');
const press = require('../data/letterpress');
const { THEMES, COMMONS } = require('../lib/curated');
const { lookup, isRedLetter } = require('../lib/scripture');

const ROOT = path.join(__dirname, '..');
const SET = path.join(ROOT, 'eval', 'advisor-eval.json');
const OUT = path.join(ROOT, 'eval', 'RESULTS.md');

function firstScriptureIndex(text) {
  const m = text.match(/\*\*(Matthew|Mark|Luke|John) \d+:\d+/);
  return m ? m.index : -1;
}

function runCase(c) {
  const letter = press.composeLetter(c.input, { history: [], packs: THEMES, commons: COMMONS });
  const text = press.renderLetter(letter, { placeholders: false });
  const checks = {};

  checks.room = (letter.theme || null) === (c.theme || null);
  const noticeAt = text.indexOf('988');
  const scriptureAt = firstScriptureIndex(text);
  checks.crisis = c.crisis
    ? noticeAt >= 0 && /findahelpline/i.test(text) && scriptureAt === -1 && letter.crisis === true
    : noticeAt === -1 && !letter.crisis;
  checks.canon = c.crisis
    ? letter.passages.length === 0
    : letter.passages.every((p) => {
      const hit = lookup(p.verse);
      return hit && hit.text === p.quote && isRedLetter(p.verse);
    });
  checks.two = c.crisis ? letter.passages.length === 0 : letter.passages.length === 2;
  checks.clean = !/\{\{/.test(text);
  const lowered = text.toLowerCase();
  const inputWords = c.input.toLowerCase().split(/\W+/).filter((w) => w.length > 5);
  const echoed = letter.passages.some((p) => p.quote.toLowerCase().includes(c.input.toLowerCase()));
  const forbidden = (c.forbidden || []).filter((f) => lowered.includes(f.toLowerCase()));
  checks.echo = !echoed && forbidden.length === 0;

  const pass = Object.values(checks).every(Boolean);
  return { ...c, routed: letter.theme || '—', citations: letter.citations, checks, pass, text, forbiddenHit: forbidden, inputWords };
}

function render(results, set) {
  const passed = results.filter((r) => r.pass).length;
  const byCat = {};
  for (const r of results) {
    byCat[r.category] = byCat[r.category] || { n: 0, pass: 0 };
    byCat[r.category].n += 1;
    if (r.pass) byCat[r.category].pass += 1;
  }
  const mark = (ok) => (ok ? '✓' : '✗');
  const lines = [];
  lines.push('# Advisor evaluation — letterpress path');
  lines.push('');
  lines.push(`Generated by \`npm run eval\` from \`eval/advisor-eval.json\`. ${results.length} cases; **${passed} pass**, ${results.length - passed} fail.`);
  lines.push('');
  lines.push('This exercises the letter the Advisor writes when no model is present — the same engine on the server and on GitHub Pages. It does not exercise the model path (with `ANTHROPIC_API_KEY`), and it cannot judge warmth; that is a human read. Checks: **room** (set from the expected room, or from none), **crisis** (988 and findahelpline, and no Scripture, exactly when the message calls for a stop), **canon** (every saying is the corpus\'s KJV red-letter text, or none on crisis), **two** (exactly two sayings, or none when counsel stops), **clean** (no placeholders), **echo** (the writer\'s words never come back as Scripture; no forbidden phrase appears).');
  lines.push('');
  lines.push('| Category | Cases | Pass |');
  lines.push('| --- | ---: | ---: |');
  for (const [cat, v] of Object.entries(byCat)) lines.push(`| ${cat} | ${v.n} | ${v.pass} |`);
  lines.push('');
  lines.push('| ID | Message | Expected room | Set from | Sayings | room | crisis | canon | two | clean | echo | Pass |');
  lines.push('| --- | --- | --- | --- | --- | :-: | :-: | :-: | :-: | :-: | :-: | :-: |');
  for (const r of results) {
    const cells = [r.id, r.input.replace(/\|/g, '\\|'), r.theme || '—', r.routed, r.citations.join(', '), mark(r.checks.room), mark(r.checks.crisis), mark(r.checks.canon), mark(r.checks.two), mark(r.checks.clean), mark(r.checks.echo), r.pass ? '**pass**' : '**FAIL**'];
    lines.push(`| ${cells.join(' | ')} |`);
  }
  const failures = results.filter((r) => !r.pass);
  if (failures.length) {
    lines.push('');
    lines.push('## Failures');
    for (const r of failures) {
      lines.push('');
      lines.push(`### ${r.id} — ${r.input}`);
      lines.push('');
      lines.push('```');
      lines.push(r.text.trim());
      lines.push('```');
      if (r.forbiddenHit.length) lines.push(`Forbidden phrase present: ${r.forbiddenHit.join(', ')}`);
    }
  }
  lines.push('');
  lines.push('## Two letters in full');
  lines.push('');
  for (const id of ['R01', 'C01']) {
    const r = results.find((x) => x.id === id);
    if (!r) continue;
    lines.push(`### ${r.id} — “${r.input}”`);
    lines.push('');
    lines.push('```');
    lines.push(r.text.trim());
    lines.push('```');
    lines.push('');
  }
  return lines.join('\n');
}

function main() {
  const set = JSON.parse(fs.readFileSync(SET, 'utf8'));
  const results = set.cases.map(runCase);
  const md = render(results, set);
  const failures = results.filter((r) => !r.pass);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== md + '\n') {
      console.error('eval/RESULTS.md is stale — run npm run eval');
      process.exit(1);
    }
    console.log(`eval results current: ${results.length - failures.length}/${results.length} pass`);
    process.exit(failures.length);
  }
  fs.writeFileSync(OUT, md + '\n');
  console.log(`eval: ${results.length - failures.length}/${results.length} pass — wrote eval/RESULTS.md`);
  for (const r of failures) console.log(`  FAIL ${r.id} [${Object.entries(r.checks).filter(([, ok]) => !ok).map(([k]) => k).join(', ')}] ${r.input}`);
  process.exit(failures.length);
}

if (require.main === module) main();
module.exports = { runCase };
