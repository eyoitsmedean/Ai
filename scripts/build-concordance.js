#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const { sealedNeeds, STOP, GRAVITY, NEED_FLOOR } = require('../lib/concordance');

const rows = sealedNeeds().map(({ id, carry, theme, verse, quote }) => ({
  id, carry, theme, verse, quote,
}));
// The room's Carrying tab scores with the same stop list, gravity rules, and
// floor as the server, so a sentence lands on the same page online and offline.
const scoring = {
  floor: NEED_FLOOR,
  stop: [...STOP],
  gravity: GRAVITY.map(([re, verse, boost]) => [re.source, verse.source, boost]),
};

const jsonPath = path.join(__dirname, '..', 'public', 'concordance.json');
fs.writeFileSync(jsonPath, JSON.stringify({
  title: 'The Concordance of Need',
  translation: 'KJV',
  count: rows.length,
  needs: rows,
}, null, 2));

const jsPath = path.join(__dirname, '..', 'public', 'data', 'concordance.js');
fs.writeFileSync(jsPath, `/* Generated by scripts/build-concordance.js — do not edit by hand. */\nwindow.RLA_CONCORDANCE = ${JSON.stringify({ count: rows.length, needs: rows, scoring })};\n`);

console.log('wrote', rows.length, 'sealed needs');
