#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const { sealedNeeds } = require('../lib/concordance');

const rows = sealedNeeds().map(({ id, carry, theme, verse, quote }) => ({
  id, carry, theme, verse, quote,
}));

const jsonPath = path.join(__dirname, '..', 'public', 'concordance.json');
fs.writeFileSync(jsonPath, JSON.stringify({
  title: 'The Concordance of Need',
  translation: 'KJV',
  count: rows.length,
  needs: rows,
}, null, 2));

const jsPath = path.join(__dirname, '..', 'public', 'data', 'concordance.js');
fs.writeFileSync(jsPath, `/* Generated by scripts/build-concordance.js — do not edit by hand. */\nwindow.RLA_CONCORDANCE = ${JSON.stringify({ count: rows.length, needs: rows })};\n`);

console.log('wrote', rows.length, 'sealed needs');
